def load_golden_set(agent_scope: str | None = None) -> list[GoldenQuery]:
    """
    Load the full golden set or a filtered subset by agent scope.

    Parameters
    ----------
    agent_scope:
        If provided, return only queries for this agent.
        One of: "planning", "research", "gis", "geology", "remote_sensing", "ml".

    Returns
    -------
    list[GoldenQuery]
        O(N) — filtered in a single pass.
    """
    if agent_scope is None:
        return GOLDEN_SET
    return [q for q in GOLDEN_SET if q.agent_scope == agent_scope]
